/** Boucle 4 : étiquettes libres et sélection multiple (étiqueter, favoris), en 390 px. */
const { chromium } = await import(process.env.PLAYWRIGHT ?? 'playwright');
const BASE = process.env.BASE ?? 'http://127.0.0.1:5180';
const OUT = process.env.OUT ?? './test-results';
const A = { user: process.env.A_USER ?? 'testeur1', pass: process.env.A_PASS ?? 'TestLocal123' };
let failures = 0;
const ok = (c, m) => (console.log(`${c ? 'OK  ' : 'FAIL'} ${m}`), c || failures++);
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true })).newPage();
p.on('pageerror', (e) => (console.log('JS', e.message), failures++));
const go = (u) => p.goto(BASE + u, { waitUntil: 'networkidle' });
await go('/login');
await p.fill('input[name=username]', A.user);
await p.fill('input[name=password]', A.pass);
await p.click('button:has-text("Se connecter")');
await p.waitForURL(BASE + '/');
await go('/album?own=owned');
await p.click('[data-testid=select-mode]');
const picks = p.locator('[data-testid=album-pick]:not(.off)');
await picks.nth(0).click();
await picks.nth(1).click();
await p.click('[data-testid=tag-selection]');
await p.fill('input[aria-label="Étiquette"]', 'Pour mon deck');
await p.screenshot({ path: `${OUT}/b4-apres-5-etiqueter.png` });
await p.click('[data-testid=tag-submit]');
await p.waitForSelector('[data-testid=toast]');
ok((await p.locator('[data-testid=toast]').innerText()).includes('Pour mon deck'), 'étiquette ajoutée à 2 cartes');
await go('/album?own=owned&tag=' + encodeURIComponent('Pour mon deck'));
ok((await p.locator('.grid-cards .card-link').count()) === 2, 'filtre par étiquette');
await p.click('[data-testid=select-mode]');
await p.locator('[data-testid=album-pick]').first().click();
await p.click('[data-testid=fav-selection]');
await p.waitForSelector('[data-testid=toast]');
ok(true, 'favoris en masse');
await p.locator('.grid-cards a.card-link').first().click();
await p.waitForURL(/\/card\/\d+/);
await p.fill('input[aria-label="Nouvelle étiquette"]', 'Rare à garder');
await p.click('[data-testid=add-tag]');
await p.waitForTimeout(600);
ok((await p.locator('[data-testid=tags] .chip').count()) >= 2, 'étiquette ajoutée depuis la fiche');
await b.close();
console.log(failures ? `${failures} échec(s)` : 'Étiquettes OK.');
process.exit(failures ? 1 : 0);
